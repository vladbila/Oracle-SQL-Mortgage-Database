CREATE SEQUENCE seq_pk
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;
CREATE TABLE SUCURSALA (
    id_sucursala NUMBER(10) PRIMARY KEY,
    nume_sucursala VARCHAR2(50) NOT NULL,
    adresa VARCHAR2(100) NOT NULL,
    oras VARCHAR2(50) NOT NULL
);

CREATE TABLE CLIENT (
    id_client NUMBER(10) PRIMARY KEY,
    cnp VARCHAR2(13) NOT NULL,
    nume VARCHAR2(50) NOT NULL,
    telefon VARCHAR2(15) NOT NULL,
    email VARCHAR2(50) UNIQUE,
    venit_net NUMBER(8,2) CHECK(venit_net > 0)
);

CREATE TABLE PRODUS_BANCAR (
    id_produs NUMBER(10) PRIMARY KEY,
    denumire VARCHAR2(50) NOT NULL,
    moneda VARCHAR2(3) CHECK (moneda in ('LEI', 'EUR')),
    marja_dobanda NUMBER(4,2) CHECK(marja_dobanda > 0)
);

CREATE TABLE IMOBIL (
    id_imobil NUMBER(10) PRIMARY KEY,
    tip_imobil VARCHAR2(20) CHECK (tip_imobil IN ('Apartament', 'Casa', 'Teren')),
    adresa VARCHAR2(150) NOT NULL,
    an_constructie NUMBER(4)
);

CREATE TABLE SERVICIU (
    id_serviciu NUMBER(10) PRIMARY KEY,
    denumire VARCHAR2(50) NOT NULL
);

CREATE TABLE ASIGURATOR (
    id_asigurator NUMBER(10) PRIMARY KEY,
    nume_companie VARCHAR2(50) UNIQUE NOT NULL,
    telefon_contact VARCHAR2(15)
);

CREATE TABLE ANGAJAT (
    id_angajat NUMBER(10) PRIMARY KEY,
    id_sucursala NUMBER(10) NOT NULL,
    nume_complet VARCHAR2(50) NOT NULL,
    data_angajare DATE NOT NULL,
    salariu NUMBER(8,2) CHECK (salariu > 0),
    CONSTRAINT fk_angajat_sucursala FOREIGN KEY (id_sucursala) REFERENCES SUCURSALA(id_sucursala)
);

CREATE TABLE CONT_CURENT (
    id_cont NUMBER(10) PRIMARY KEY,
    id_client NUMBER(10) NOT NULL,
    iban VARCHAR2(24) UNIQUE NOT NULL,
    moneda VARCHAR2(3) DEFAULT 'LEI' CHECK (moneda IN ('LEI', 'EUR')),
    CONSTRAINT fk_cont_client FOREIGN KEY (id_client) REFERENCES CLIENT(id_client)
);

CREATE TABLE OFITER_CREDIT (
    id_angajat NUMBER(10) PRIMARY KEY,
    grad_ofiter VARCHAR2(20) DEFAULT 'Junior' CHECK (grad_ofiter IN ('Junior', 'Senior')),
    CONSTRAINT fk_ofiter_angajat FOREIGN KEY (id_angajat) REFERENCES ANGAJAT(id_angajat)
);

CREATE TABLE ANALIST_RISC (
    id_angajat NUMBER(10) PRIMARY KEY,
    limita_aprobare NUMBER(10,2) CHECK (limita_aprobare > 0),
    CONSTRAINT fk_analist_angajat FOREIGN KEY (id_angajat) REFERENCES ANGAJAT(id_angajat)
);

CREATE TABLE EVALUATOR (
    id_angajat NUMBER(10) PRIMARY KEY,
    nr_autorizatie VARCHAR2(20) UNIQUE NOT NULL,
    CONSTRAINT fk_evaluator_angajat FOREIGN KEY (id_angajat) REFERENCES ANGAJAT(id_angajat)
);

CREATE TABLE EVALUARE_IMOBIL (
    id_evaluare NUMBER(10) PRIMARY KEY,
    id_imobil NUMBER(10) NOT NULL,
    id_angajat NUMBER(10) NOT NULL,
    data_evaluare DATE DEFAULT SYSDATE NOT NULL,
    valoare_estimata NUMBER(10,2) CHECK (valoare_estimata > 0),
    CONSTRAINT fk_evaluare_imobil FOREIGN KEY (id_imobil) REFERENCES IMOBIL(id_imobil),
    CONSTRAINT fk_evaluare_angajat FOREIGN KEY (id_angajat) REFERENCES EVALUATOR(id_angajat)
);

CREATE TABLE DOSAR_CREDIT (
    id_dosar NUMBER(10) PRIMARY KEY,
    id_client NUMBER(10) NOT NULL,
    id_produs NUMBER(10) NOT NULL,
    id_imobil NUMBER(10) NOT NULL,
    id_angajat NUMBER(10) NOT NULL,
    id_sucursala NUMBER(10) NOT NULL,
    id_dosar_refinantat NUMBER(10),
    suma_solicitata NUMBER(10,2) CHECK (suma_solicitata > 0),
    perioada_luni NUMBER(3) CHECK (perioada_luni BETWEEN 12 AND 360),
    data_cerere DATE DEFAULT SYSDATE NOT NULL,
    status VARCHAR2(20) DEFAULT 'In analiza' CHECK (status IN ('In analiza', 'Aprobat', 'Respins', 'Activ', 'Finalizat')),
    CONSTRAINT fk_dosar_client FOREIGN KEY (id_client) REFERENCES CLIENT(id_client),
    CONSTRAINT fk_dosar_produs FOREIGN KEY (id_produs) REFERENCES PRODUS_BANCAR(id_produs),
    CONSTRAINT fk_dosar_imobil FOREIGN KEY (id_imobil) REFERENCES IMOBIL(id_imobil),
    CONSTRAINT fk_dosar_ofiter FOREIGN KEY (id_angajat) REFERENCES OFITER_CREDIT(id_angajat),
    CONSTRAINT fk_dosar_sucursala FOREIGN KEY (id_sucursala) REFERENCES SUCURSALA(id_sucursala),
    CONSTRAINT fk_dosar_refinantat FOREIGN KEY (id_dosar_refinantat) REFERENCES DOSAR_CREDIT(id_dosar)
);

CREATE TABLE RATA (
    id_rata NUMBER(10) PRIMARY KEY,
    id_dosar NUMBER(10) NOT NULL,
    id_cont NUMBER(10),
    numar_rata NUMBER(3) CHECK (numar_rata > 0),
    data_scadenta DATE NOT NULL,
    valoare_plata NUMBER(8,2) CHECK (valoare_plata > 0),
    status VARCHAR2(20) DEFAULT 'Neplatit' CHECK (status IN ('Neplatit', 'Platit Partial', 'Achitat complet')),
    CONSTRAINT fk_rata_dosar FOREIGN KEY (id_dosar) REFERENCES DOSAR_CREDIT(id_dosar),
    CONSTRAINT fk_rata_cont FOREIGN KEY (id_cont) REFERENCES CONT_CURENT(id_cont)
);

CREATE TABLE POLITA_ASIGURARE (
    id_dosar NUMBER(10),
    id_serviciu NUMBER(10),
    id_asigurator NUMBER(10),
    numar_polita VARCHAR2(30) UNIQUE NOT NULL,
    data_emitere DATE DEFAULT SYSDATE NOT NULL,
    cost_prima NUMBER(8,2) CHECK (cost_prima > 0),
    CONSTRAINT pk_polita PRIMARY KEY (id_dosar, id_serviciu, id_asigurator),
    CONSTRAINT fk_polita_dosar FOREIGN KEY (id_dosar) REFERENCES DOSAR_CREDIT(id_dosar),
    CONSTRAINT fk_polita_serviciu FOREIGN KEY (id_serviciu) REFERENCES SERVICIU(id_serviciu),
    CONSTRAINT fk_polita_asigurator FOREIGN KEY (id_asigurator) REFERENCES ASIGURATOR(id_asigurator)
);

